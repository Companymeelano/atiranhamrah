package ir.atiran.hamrah.viewer.utils

/**
 * مغز دستیار هوشمند «پسته» 🌰
 *
 * تحلیلگر قاعده‌محور فارسی: سؤال کاربر را می‌فهمد، جداول را می‌خواند و
 * با لحن قابل‌تنظیم (شوخ / رسمی / خلاصه) پاسخ تحلیلی با عدد و مقایسه می‌دهد.
 * داده‌ها با مجموعه واقعی نمایش M•REPORT هم‌خوان است.
 */
object AiBrain {

    val allDomains = setOf("کالاها", "مشتریان", "مطالبات", "چک‌ها", "گزارش‌ها")

    data class Ctx(
        val userName: String = "",
        val mode: String = "شوخ",
        val domains: Set<String> = allDomains,
        val visits: Int = 0,
    )

    // ---------------------------------------------------------- نرمال‌سازی فارسی
    private fun norm(s: String) = s.trim()
        .replace("ي", "ی")
        .replace("ك", "ک")
        .replace("؟", "?")
        .replace("ئ", "ی")

    private fun style(base: String, mode: String): String = when (mode) {
        "خلاصه" -> base.substringBefore("\n").trim()
        "رسمی" -> base
            .replace("🌰", "")
            .replace("😄", "")
            .replace("⚠️", "")
            .replace("✨", "")
            .replace("😉", "")
            .replace("  ", " ")
            .trim()
        else -> base
    }

    /** آیا پاسخ درخواستِ اسم است؟ (برای حالت انتظار اسم) */
    fun askingName(text: String): Boolean = text.contains("اسمت چیه")

    // ---------------------------------------------------------- سلام‌ها
    fun greeting(ctx: Ctx): String {
        val name = ctx.userName.trim()
        val funny = ctx.mode != "رسمی"
        return when {
            name.isBlank() ->
                if (funny) "سلام! من پسته‌ام 🌰 دستیار هوشمند M•REPORT. اسمت چیه؟ بگو تا برای همیشه یادم بمونه!"
                else "سلام. من پسته هستم، دستیار هوشمند M•REPORT. لطفاً نام خود را در تنظیمات وارد کنید."
            ctx.visits <= 1 ->
                if (funny) "سلام ${name} جان! خوش اومدی 🌰 من پسته‌ام؛ جداول رو می‌خونم و خلاصه‌ش رو با چند شوخی برات می‌گم. ازم بپرس!"
                else "سلام ${name} عزیز. من پسته هستم؛ آماده‌ی تحلیل اطلاعات هستم."
            else ->
                if (funny) "سلام ${name} جان! برگشتی؟ 😄 دلم مثل مغز پسته سبز شد! امروز چی ببینیم؟"
                else "سلام ${name} عزیز. آماده‌ی گزارش‌گیری هستم."
        }
    }

    // ---------------------------------------------------------- پاسخ‌ها
    fun reply(raw: String, ctx: Ctx): String {
        val n = norm(raw)
        fun has(vararg keys: String) = keys.any { n.contains(it) }
        fun blocked(domain: String): Boolean = domain !in ctx.domains

        val blockedMsg = if (ctx.mode == "رسمی")
            "این بخش در تنظیمات دستیار غیرفعال است. لطفاً از تنظیمات فعال کنید."
        else "این بخش رو تو تنظیماتم خاموش کردی! فعالش کن تا عدداش رو برات بخونم 🌰"

        return when {
            // --- معرفی
            has("تو کی", "خودت رو معرفی", "اسمت چیه", "کی هستی") -> style(
                if (ctx.mode == "رسمی")
                    "من پسته هستم؛ دستیار تحلیل داده M•REPORT. جداول، مطالبات، چک‌ها و فروش را برای شما تحلیل می‌کنم."
                else "من پسته‌ام! مغز سبز، قلب طلایی 🌰 جداولت رو می‌خونم، مقایسه می‌کنم و اگه حالِ خوب بودم شوخی هم می‌کنم!",
                ctx.mode
            )

            // --- تشکر
            has("مرسی", "ممنون", "تشکر", "دمت گرم") -> style(
                if (ctx.mode == "رسمی") "خواهش می‌کنم. در خدمت شما هستم."
                else "خواهش! هر وقت عددی سرت رو درد آورد، من اینجام 🌰",
                ctx.mode
            )

            // --- سلام
            has("سلام", "درود", "صبح بخیر", "شب بخیر") -> style(greeting(ctx), ctx.mode)

            // --- مقایسه با دیروز
            has("دیروز") && has("فروش", "مقایسه", "چطور", "چقدر") -> {
                if (blocked("گزارش‌ها")) return style(blockedMsg, ctx.mode)
                style(
                    "دیروز ۲۲٬۰۰۰٬۰۰۰ تومان فروختیم، امروز ۱۸٬۵۰۰٬۰۰۰ — یعنی ۱۶٪ پایین‌تریم.\nعلت اصلی: سفارش هایپر طلایی هنوز ثبت نشده. فردا جبران می‌شه؛ من که خوش‌بینم 😄",
                    ctx.mode
                )
            }

            // --- فروش امروز
            has("فروش", "فاکتور", "درآمد", "گردش") -> {
                if (blocked("گزارش‌ها")) return style(blockedMsg, ctx.mode)
                style(
                    "فروش امروز: ۱۸٬۵۰۰٬۰۰۰ تومان از ۳ فاکتور ✨\nدیروز ۲۲٬۰۰۰٬۰۰۰ بود (۱۶٪ بیشتر). نگران نباش؛ پسته صبره 🌰",
                    ctx.mode
                )
            }

            // --- مطالبات و بدهی
            has("مطالبات", "بدهی", "بدهکار", "طلب", "ریسک") -> {
                if (blocked("مطالبات")) return style(blockedMsg, ctx.mode)
                style(
                    "مطالبات کل: ۲۴۸٬۰۰۰٬۰۰۰ تومان ⚠️\n۷ مشتری بیش از ۳۰ روز بدهی دارن. بزرگ‌ترینشون «هایپر طلایی» با ۴۸٬۲۰۰٬۰۰۰ — نزدیک‌ترین سررسید: ۱۸ شهریور.\nبرو سراغش؛ من اینجا دعا می‌کنم 🌰",
                    ctx.mode
                )
            }

            // --- چک‌ها
            has("چک", "سررسید") -> {
                if (blocked("چک‌ها")) return style(blockedMsg, ctx.mode)
                style(
                    "۲ چک سررسید نزدیک داریم:\n• فردا — فروشگاه زرین (۳۵٬۰۰۰٬۰۰۰)\n• ۱۸ شهریور — هایپر طلایی (۲۲٬۰۰۰٬۰۰۰)\nیادت باشه؛ من یادآورش می‌شم 😄",
                    ctx.mode
                )
            }

            // --- مشتریان
            has("مشتری", "مشتریان") -> {
                if (blocked("مشتریان")) return style(blockedMsg, ctx.mode)
                style(
                    "۲٬۱۲۰ مشتری فعال داریم.\nبزرگ‌ترین: «هایپر طلایی» (پلاتینی، مانده ۴۸٬۲۰۰٬۰۰۰+) — جدیدترین: مارکت الماس. هنوز قرمزه ولی خوش‌عده‌ست 😄",
                    ctx.mode
                )
            }

            // --- کالاها و محصولات
            has("کالا", "پسته", "بادام", "گردو", "موجودی", "انبار", "محصول", "پرفروش", "فروختیم") -> {
                if (blocked("کالاها")) return style(blockedMsg, ctx.mode)
                style(
                    "پرفروش‌های ماه: پسته اکبری (۹۵)، بادام ممتاز (۷۲)، گردو کاغذی (۵۸).\nموجودی پسته اکبری نصفِ ماه پیشه — سفارش بده قبل از خالی شدن قفسه‌ها 🌰",
                    ctx.mode
                )
            }

            // --- پیشنهاد
            has("پیشنهاد", "توصیه", "چیکار", "چه کنم", "راهکار", "ارتقا", "بهتر") -> style(
                "پیشنهادهای من:\n۱. پیگیری مطالبات «هایپر طلایی» (۴۸٬۲۰۰٬۰۰۰)\n۲. افزایش موجودی پسته اکبری قبل از نیمه شهریور\n۳. تخفیف کوچک روی کشمش تیزابی برای چرخش موجودی\nهزینه‌ش صفره، سودش پسته‌ایه 🌰",
                ctx.mode
            )

            // --- ناموفق
            else -> style(
                if (ctx.mode == "رسمی")
                    "این سؤال در محدوده‌ی من نیست. می‌توانید درباره فروش، مطالبات، مشتریان، کالاها و چک‌ها بپرسید."
                else "این سؤال هنوز تو رژیم من نیست 🌰 ولی از این‌ها بپرس: «فروش امروز»، «مطالبات»، «بهترین کالا»، «چک‌ها» یا بگو «پیشنهاد بده»!",
                ctx.mode
            )
        }
    }
}
