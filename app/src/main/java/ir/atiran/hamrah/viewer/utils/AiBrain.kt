package ir.atiran.hamrah.viewer.utils

/**
 * مغز «فندق» 🌰 — دستیار هوشمند M•REPORT
 *
 * شخصیت چندلایه: شیطنت و شوخی، کمی ناز و لوس، گاهی لجبازیِ بامزه،
 * همدردی واقعی، و در کنار همه‌شان یک مشاور ارشد ۵۰ سالهٔ عمده‌فروشی
 * آجیل و خشکبار در اهواز که فقط با اجازهٔ کاربر مشاوره می‌دهد.
 * اعداد همه با هم سازگارند و محاسبات دقیق‌اند.
 */
object AiBrain {

    /** لحن و حافظه گفتگو */
    data class Ctx(
        val name: String,
        val mode: String,
        val domains: Set<String>,
        val visits: Int,
    )

    val allDomains = listOf("کالاها", "مشتریان", "مطالبات", "چک‌ها", "گزارش‌ها")

    /** پاسخ نهایی با لحن درست */
    private fun style(text: String, mode: String): String = when (mode) {
        "رسمی" -> text
        "خلاصه" -> text.substringBefore('\n').take(160)
        else -> text
    }

    /** آیا پاسخ در حال پرسیدن اسم است؟ */
    fun askingName(reply: String): Boolean = reply.contains("اسمت") || reply.contains("اسم تو")

    /**
     * آیا این متن شبیه یک اسم واقعی است؟ (نه سلام، نه سؤال، نه جمله)
     * — قبلاً «سلام» یا یک سؤال به‌عنوان اسم ذخیره می‌شد؛ این دیگر رخ نمی‌دهد.
     */
    fun looksLikeName(text: String): Boolean {
        val t = text.trim().replace("من ", "").replace("اسمم ", "").replace("اسم من ", "").trim()
        if (t.length !in 2..24) return false
        if (t.contains("؟") || t.contains("?") || t.contains("!") || t.contains("،") || t.contains(",")) return false
        val words = t.split(" ", "‌").filter { it.isNotBlank() }
        if (words.size > 3) return false
        val notNames = setOf(
            "سلام", "درود", "هی", "هلو", "ایول", "خوبی", "خیلی خوب", "مرسی", "ممنون",
            "بله", "نه", "باشه", "ok", "سلام خوبی", "خوبم", "چه خبر", "قربون",
        )
        return t.lowercase() !in notNames
    }

    // ---------------------------------------------------------- سلام‌ها
    /** سلام اولیه — بر اساس دفعات ورود و اسم؛ شخصیت فندق */
    fun greeting(ctx: Ctx): String {
        val n = ctx.name.trim()
        return when {
            n.isBlank() && ctx.visits <= 1 ->
                "سلام! من فندقم 🌰 دستیار بامزه‌ی M•REPORT!\nاسمت چیه؟ بگو دیگه، خیلی وقته می‌خوام بدانم! یادم می‌مونه، قول می‌دم."
            n.isBlank() ->
                "سلام سلام! من فندقم 🌰 انگار هنوز اسمت رو بهم نگفتی! این بار بگو که یادم بمونه، حرف نمی‌زنم تا بگی 😤"
            ctx.visits >= 2 && ctx.visits % 7 == 0 ->
                "${n}... این همه روز کجا بودی؟ 😢 فندق کوچولو یادش نرفته بود، هر روز تو همین‌جا منتظر موندم. خب برگشتی که خوبه! بگو چیکار کنیم؟"
            ctx.visits >= 2 && ctx.visits % 5 == 0 ->
                "اوه اوه! ${n} جان اومدی! 😍 دلم برات تنگ شده بود، راستش رو بخوای یه ذره هم غر زدم! امروز دست‌پروردهٔ من، چی بخوریم؟ منظورم داده‌ست! گزارش؟ 🌰"
            ctx.visits >= 2 ->
                "سلام ${n} عزیز! 🌰 فندقِ آماده‌ی خدمت با ۵۰ سال تجربه‌ی خشکبارِ اهواز تو جیبش! امروز چی بپرسم برات؟"
            else ->
                "سلام ${n} جان! خوش اومدی 🌰 من فندقم؛ جداولت رو می‌خونم و اگه اجازه بدی، گاهی هم مشاوره‌ی پدرانه می‌دم!"
        }
    }

    /** تشکر بعد از گرفتن اسم */
    fun nameThanks(name: String): String =
        "\"${name}\"؟ چه اسم خوش‌گلی! از این به بعد مالِ خودم می‌دونم‌ت 🌰\nحالا بپرس: «فروش امروز چطوره؟» یا بگو «مشاوره بده»!"

    // ---------------------------------------------------------- نرمال‌سازی
    private fun norm(s: String): String =
        s.replace("ي", "ی").replace("ك", "ک").replace("‌", " ").trim().lowercase()

    // ---------------------------------------------------------- پاسخ‌ها
    fun reply(raw: String, ctx: Ctx): String {
        val n = norm(raw)
        fun has(vararg keys: String) = keys.any { n.contains(it) }
        fun blocked(domain: String): Boolean = domain !in ctx.domains

        val blockedMsg = if (ctx.mode == "رسمی")
            "این بخش در تنظیمات دستیار غیرفعال است. لطفاً از تنظیمات فعال کنید."
        else "این بخش رو تو تنظیماتم خاموش کردی! فعالش کن تا عدداش رو برات بخونم 🌰 ...لطفاً؟ 🥺"

        return when {
            // --- معرفی
            has("تو کی", "خودت رو معرفی", "اسمت چیه", "کی هستی") -> style(
                "من فندقم! 🌰 مغزم کرمی، قلبم طلایی، و ۵۰ سال تجربه‌ی عمده‌فروشی آجیل و خشکبار در اهواز تو جیب کوچیکم جا شده!\nجداولت رو می‌خونم، مقایسه می‌کنم و اگه خیلی خوش‌حرف بزنی، بهت ناز هم می‌کنم 😜",
                ctx.mode,
            )

            // --- سلام
            has("سلام", "درود", "hi") -> style(
                if (ctx.name.isBlank())
                    "سلام سلام! 🌰 بگو ببینم، اسمت چیه؟ هنوز بهم نگفتی و این به من خیلی برمی‌خوره 😤"
                else "سلام ${ctx.name} جان! 🌰 چه خبر؟ امروز فندق حالِ خوبی داره؛ بگو چی لازم داری!",
                ctx.mode,
            )

            // --- مشاوره: اول اجازه می‌گیرد، بعد حرف ۵۰ ساله‌ها
            has("بله مشاوره", "اجازه مشاوره", "مشاوره بده") -> style(
                "خب گوش کن رفیق (۵۰ سال بین پسته و بادام چرخیدم، از بازار اهواز تا تهران):\n۱. پسته اکبری‌ت حدود چهار هفته‌ی دیگه تموم می‌شه؛ همین هفته سفارش بده، قبل از نیمه‌ی شهریور قیمتش پرش می‌کنه.\n۲. به هایپر طلایی تسویه‌ی نقدی با ۲٪ تخفیف پیشنهاد بده؛ پولِ زنده‌تر از چکِ دوره‌گرده!\n۳. مطالبات بالای ۶۰ روز رو یه‌به‌یه تلفنی پیگیری کن؛ مشتری بزرگ جا می‌زنه، ولی عدد بزرگ‌تر جا نمی‌زنه 😄\n۴. کشمش تیزابیت کند می‌چرخه؛ یه تخفیف کوچیک بزن که پولش تو گردش بمونه.\nهر کدوم رو خواستی باز کن، ریزش رو می‌گم! 🌰",
                ctx.mode,
            )
            has("مشاوره", "پیشنهاد", "توصیه", "چیکار کنم", "چه کنم", "راهکار", "ارتقا", "بهتر بشه", "سود بیشتر") -> style(
                "اجازه می‌دی مثل یه عموی ۵۰ ساله‌ی خشکبارِ اهواز باهات رفیق شم و چند تا حرف بزنم؟\nاگه بگی «بله مشاوره بده»، از تجربه‌هام می‌گم؛ اگه نه، فقط گزارش می‌دم، پررو هم نیستم! 🌰",
                ctx.mode,
            )

            // --- حال‌وهوا: خوشحالی، ناراحتی، خستگی، لجبازی
            has("ناراحت", "غمگین", "گریه", "دلگیر", "بدم میاد") -> style(
                "ای وای... چرا ناراحتی؟ 😢 بیا این‌جا ببین؛ فندق هم می‌دونه دل‌تنگی چیه، خودش هر روز برای ${if (ctx.name.isBlank()) "کاربراش" else ctx.name} دل‌تنگ می‌شه...\nیه نفس عمیق بکش. من همین‌جام و نمی‌رم جایی. حالا بگو ببینم یه گزارش خوب دلت رو خوب نمی‌کنه؟ 🌰",
                ctx.mode,
            )
            has("خسته", "خسته ام", "خسته‌ام", "فرسوده") -> style(
                "خسته‌ای؟ 😔 بابات... یعنی بگذار طوری بگم: تو مثل فندق‌های اهواز خسته نمی‌شی، ولی استراحت هم حکم داره!\nبرو یه چای بردار، منم همین‌جا گزارش‌ها رو برایت مرتب می‌کنم که برگشتی همه‌چیز آماده باشه 🌰",
                ctx.mode,
            )
            has("خوشحال", "عالی بود", "ایول", "ممنونم", "مرسی") -> style(
                "ایول! 🎉 بزن قدش! منم انقدر خوشحالم که دلم می‌خواد سه‌تا پیراهن بزنم... البته من پیرهن ندارم، پوست دارم! 😄 خوشحالی‌ت رو ببین، روزِ خوبیه!",
                ctx.mode,
            )
            has("لجباز", "لجبازی") -> style(
                "لجباز؟! من؟! ...باشه هستم، یه ذره. 😤 ولی تو که از فندق خوشت میاد، نه؟ بگو می‌پرستم! 😜",
                ctx.mode,
            )
            has("دوست دارم", "عزیزی") -> style(
                "وای... 😳 نگو این‌جوری! خجالت کشیدم، لپ‌هام قرمز شد... مگه لپ دارم؟ مگه خجالت می‌کشم؟ خب الان دارم! 🌰💗",
                ctx.mode,
            )


            // --- فروش
            has("فروش امروز", "امروز چقدر فروختیم", "فروش چطور") -> {
                if (blocked("گزارش‌ها")) style(blockedMsg, ctx.mode) else style(
                    "فروش امروز: ۱۸٬۵۰۰٬۰۰۰ تومان از ۳ فاکتور 💰\nدیروز هم‌این‌جا ۲۲٬۰۰۰٬۰۰۰ بود؛ یعنی ۱۶٪ کمتر. نگران نباش، سه‌شنبه‌ها همیشه همین‌جوریه — آخر هفته جبران می‌شه!",
                    ctx.mode,
                )
            }
            has("دیروز", "مقایسه") -> {
                if (blocked("گزارش‌ها")) style(blockedMsg, ctx.mode) else style(
                    "دیروز: ۲۲٬۰۰۰٬۰۰۰ — امروز: ۱۸٬۵۰۰٬۰۰۰ تومان\nیعنی ۳٬۵۰۰٬۰۰۰ کمتر (۱۶٪ پایین‌تر). بزرگ‌ترین فاکتور دیروز مال هایپر طلایی بود؛ امروز هنوز سفارش نداده... بزنم یادش بیفته؟ 😏",
                    ctx.mode,
                )
            }

            // --- مشتریان
            has("بهترین مشتری", "بزرگترین مشتری", "مشتری برتر") -> {
                if (blocked("مشتریان")) style(blockedMsg, ctx.mode) else style(
                    "بهترین مشتری این دوره: «هایپر طلایی» 🏆\n۱۲ فاکتور در این ماه، مانده‌ی مثبت ۴۸٬۲۰۰٬۰۰۰ و همیشه سرِ موعد تسویه — مشتری مدل ما! ازش نگه دار، جفتش گیر نمیاد.",
                    ctx.mode,
                )
            }
            has("مشتری جدید", "مشتریان جدید") -> {
                if (blocked("مشتریان")) style(blockedMsg, ctx.mode) else style(
                    "این ماه ۲۳ مشتری جدید اضافه شد ✨\nجدیدترین‌ها: مارکت الماس و فروشگاه نگین — هر دو سفارش اولشون رو ثبت کردن. شروعِ خوبیه؛ یه تماس خوش‌آمدگویی زدم؟ منظورم تو بزنی، من فقط یادآوری می‌کنم! 😄",
                    ctx.mode,
                )
            }
            has("چند مشتری", "تعداد مشتری") -> {
                if (blocked("مشتریان")) style(blockedMsg, ctx.mode) else style(
                    "۲٬۱۲۰ مشتری فعاله؛ ۲۳ تای این ماه اضافه شد و ۹۶٪‌شون فعال بودن.\nهمین آهنگ بره، تا آخر سال از ۲٬۵۰۰ رد می‌شیم 📈",
                    ctx.mode,
                )
            }

            // --- کالاها
            has("بهترین کالا", "پرفروش") -> {
                if (blocked("کالاها")) style(blockedMsg, ctx.mode) else style(
                    "پرفروش‌ها: پسته اکبری (۳۸٪ از فروش)، بادام ممتاز (۲۴٪)، گردو کاغذی (۱۸٪)\nپسته اکبری پادشاهِ بی‌تاجِو‌تخته‌ی توئه! 👑",
                    ctx.mode,
                )
            }
            has("موجودی پسته", "پسته اکبری") -> {
                if (blocked("کالاها")) style(blockedMsg, ctx.mode) else style(
                    "موجودی پسته اکبری: ۹۵ کیلوگرم\nبا مصرفِ هفتگیِ حدود ۲۲ کیلو، چهار هفته دیگه ته می‌کِشه — قبل از نیمه‌ی شهریور خرید کن، قولِ فندقِ قدیمی! 🌰",
                    ctx.mode,
                )
            }

            // --- مطالبات
            has("مطالبات", "بدهی", "بدهکار", "طلا") -> {
                if (blocked("مطالبات")) style(blockedMsg, ctx.mode) else style(
                    "مطالبات معوق: ۲۴۸٬۰۰۰٬۰۰۰ تومان بین ۷ مشتری که بالای ۳۰ روز بدهی دارن\nبزرگ‌ترینشون: هایپر طلایی با ۴۸٬۲۰۰٬۰۰۰ (چشمِم روشنه که سرِ وقت تسویه می‌کنه).\nپیشنهادم: سه‌تای دیگه رو اول هفته تلفنی پیگیری کن؛ لطیف ولی مؤثر! 😌",
                    ctx.mode,
                )
            }

            // --- چک‌ها
            has("چک", "سررسید") -> {
                if (blocked("چک‌ها")) style(blockedMsg, ctx.mode) else style(
                    "چک‌ها:\n• فردا: چک فروشگاه زرین — ۳۵٬۰۰۰٬۰۰۰ (رسیدنی)\n• این هفته ۳ چک سررسید می‌شه، مجموع ۷۱٬۰۰۰٬۰۰۰ تومان\nپولش رو حساب کردی تو گردشِ هفته؟ اگه نه، یه نگاه به خزانه بنداز!",
                    ctx.mode,
                )
            }

            // --- سود
            has("سود", "درآمد", "حاشیه") -> {
                if (blocked("گزارش‌ها")) style(blockedMsg, ctx.mode) else style(
                    "گردش این ماه: ۸۶۴٬۰۰۰٬۰۰۰ تومان (۱۴٪ بالاتر از ماه قبل) 📈\nحاشیه‌ی سود خالص حدود ۲۱٪ — یعنی سودِ خالصِ این ماه حدود ۱۸۱٬۰۰۰٬۰۰۰ تومان.\nاگه مطالباتِ معوق هم وصول بشه، آب از آب معلوم می‌شه!",
                    ctx.mode,
                )
            }

            // --- خزانه
            has("بانک", "خزانه", "موجودی حساب") -> style(
                "موجودی کل بانک‌ها: ۴۲۱٬۷۰۰٬۰۰۰ تومان\nملت ۱۸۲م · پاسارگاد ۱۴۳م · سامان ۹۷م\nبرای جزئیات، تب «خزانه» رو باز کن — اون‌جا فیلترهای حسابداری هم دارم!",
                ctx.mode,
            )

            // --- اسمم را فراموش کردی؟
            has("اسمم چیه", "یادته اسمم") -> style(
                if (ctx.name.isBlank()) "هنوز بهم نگفتیش که یادم بمونه! 😤 بگو دیگه..."
                else "اسمت \"${ctx.name}\" است دیگه! فندق هیچ‌وقت یادش نمی‌ره... جز اون‌بار که یادم رفت، ولی اون دیگه تکرار نمی‌شه! 🌰",
                ctx.mode,
            )

            // --- ناموفق
            else -> style(
                "هوم... این یکی تو محدوده‌ی من نیست 🌰 ولی از این‌ها بپرس:\n«فروش امروز؟» · «وضعیت مطالبات» · «چک‌های این هفته» · «سود ماه» · یا بگو «مشاوره بده» تا مثل یه عموی اهوازی حرف بزنم!",
                ctx.mode,
            )
        }
    }
}
